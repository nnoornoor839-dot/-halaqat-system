-- ============================================================
-- التطبيق يفحص «هل صدرت التذكرة؟» في JavaScript ثم يُدرج
-- (web/app/tickets/page.js). وهذا نمط «اقرأ ثم اكتب»: لو ضغط مشرفان في
-- اللحظة نفسها، كلاهما يقرأ «لم تصدر» فتصدر تذكرتان — ومعها مطالبة
-- مالية مضاعفة. القيد يقفلها في القاعدة لا في التوقيت.
--
-- لا يُشغَّل على قاعدة جديدة: القيد مدمج في schema.sql أصلاً. هذا الملف
-- لترقية قاعدة أُنشئت قبله.
--
-- الحالة: مُطبَّق.
--
-- ------------------------------------------------------------
-- ملاحظة منهجية تستحق البقاء
-- ------------------------------------------------------------
-- حوى هذا الملف في نسخته الأولى قيداً ثانياً على users.role، بناءً على
-- أن القاعدة الحيّة بلا ذلك القيد. وكان الاستنتاج خاطئاً: القيد موجود
-- منذ البداية، لكن استعلام قراءة المخطط رجع مقطوعاً عند 100 صف
-- (الحد الافتراضي في محرّر Supabase)، والقطع وقع داخل صفوف users فأخفى
-- مفتاحها الأساسي وقيدها معاً.
--
-- الدليل كان ظاهراً وفات: users وحده ظهر بلا PRIMARY KEY بين كل
-- الجداول. جدول بلا مفتاح أساسي مستبعد، فكان الأولى الشك في اكتمال
-- النتيجة قبل البناء عليها.
--
-- الدرس: عند قراءة المخطط من المحرّر، اضبط Limit على No limit، وتحقق
-- أن كل جدول ظهر معه مفتاحه الأساسي قبل استنتاج أي نقص.
-- ============================================================

-- فحص قبلي: يجب أن يعود صفراً
select count(*) as duplicate_tickets
from (
  select student_id, week_start
  from weekly_tickets
  group by student_id, week_start
  having count(*) > 1
) d;


alter table weekly_tickets
  add constraint weekly_tickets_student_week_unique
  unique (student_id, week_start);
