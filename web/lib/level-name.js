// تسمية المستوى برقمه الترتيبي العربي (المستوى الأول، الثاني، …).
// الرقم يحدده النظام تلقائياً حسب ترتيب مستويات الطالب، ولا يكتبه المشرف يدوياً.
const ORDINALS = [
  '',
  'الأول',
  'الثاني',
  'الثالث',
  'الرابع',
  'الخامس',
  'السادس',
  'السابع',
  'الثامن',
  'التاسع',
  'العاشر',
  'الحادي عشر',
  'الثاني عشر',
  'الثالث عشر',
  'الرابع عشر',
  'الخامس عشر',
];

export function levelName(number) {
  if (!number) return 'بلا مستوى';
  return ORDINALS[number] ? `المستوى ${ORDINALS[number]}` : `المستوى ${number}`;
}

// حجم وحدة المراجعة يعتمد على رقم المستوى (يُستخدم لاحقاً في نظام المراجعة):
// المستوى الأول والثاني → نصف حزب، الثالث فما فوق → حزب.
export function reviewUnitQuarters(levelNumber) {
  return levelNumber >= 3 ? 4 : 2;
}

// بوابة تسليم السورة تنطبق من المستوى الثاني فما فوق فقط.
export function requiresSurahDelivery(levelNumber) {
  return levelNumber >= 2;
}
